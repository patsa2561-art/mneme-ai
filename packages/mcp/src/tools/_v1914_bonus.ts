export const csqRecordTool: MnemeTool = {
  name: "mneme.consequence.record",
  category: "lab",
  description:
    "⏳ CSQ — log a CLI run + caller-supplied repo state digest. Returns the run id; pass it back to mneme.consequence.record_delta at T+24h.",
  whenToUse: "After every meaningful Mneme command — to enable causal-aware queries later.",
  triggers: ["consequence record", "log run"],
  inputSchema: {
    type: "object",
    properties: {
      cmd: { type: "string" },
      args: { type: "object" },
      result: {},
      repoStateBefore: { type: "string", description: "Any digest the caller chooses (git sha, filesystem hash, etc.)." },
    },
    required: ["cmd", "result", "repoStateBefore"],
  },
  outputSchema: { type: "object" },
  examples: [{ userQuery: "Log mneme verify", args: { cmd: "mneme.verify", result: { ok: true }, repoStateBefore: "deadbeef" }, expectedOutput: "{ runId, totalRecords }" }],
  pitfalls: ["The repoStateBefore semantics are caller-defined; stay consistent within a project."],
  handler: async (_rt, args) => {
    const core = await import("@mneme-ai/core");
    const ledger = await getCsq();
    const next = core.consequenceLedger.recordRun({
      ledger,
      cmd: String(args["cmd"]),
      args: (args["args"] as Record<string, unknown>) ?? {},
      result: args["result"],
      repoStateBefore: String(args["repoStateBefore"]),
    });
    await setCsq(next);
    const newest = next.records[next.records.length - 1]!;
    return { data: { runId: newest.id, totalRecords: next.records.length }, wisdom: `⏳ logged ${newest.cmd} (id=${newest.id})`, confidence: { level: "high" } };
  },
};

