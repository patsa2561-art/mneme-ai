// Singletons per MCP server lifetime.
let dreamLedger: import("@mneme-ai/core").cliDreams.DreamLedger | null = null;
async function getDreams(): Promise<import("@mneme-ai/core").cliDreams.DreamLedger> {
  if (!dreamLedger) {
    const core = await import("@mneme-ai/core");
    dreamLedger = core.cliDreams.emptyDreamLedger();
  }
  return dreamLedger;
}
async function setDreams(next: import("@mneme-ai/core").cliDreams.DreamLedger): Promise<void> {
  dreamLedger = next;
}

let chimera: import("@mneme-ai/core").chimeraEmbedder.ChimeraEmbedder | null = null;
async function getChimera(): Promise<import("@mneme-ai/core").chimeraEmbedder.ChimeraEmbedder> {
  if (!chimera) {
    const core = await import("@mneme-ai/core");
    chimera = core.chimeraEmbedder.createChimera();
  }
  return chimera;
}

let csqLedger: import("@mneme-ai/core").consequenceLedger.ConsequenceLedger | null = null;
async function getCsq(): Promise<import("@mneme-ai/core").consequenceLedger.ConsequenceLedger> {
  if (!csqLedger) {
    const core = await import("@mneme-ai/core");
    csqLedger = core.consequenceLedger.emptyConsequenceLedger();
  }
  return csqLedger;
}
async function setCsq(next: import("@mneme-ai/core").consequenceLedger.ConsequenceLedger): Promise<void> {
  csqLedger = next;
}

