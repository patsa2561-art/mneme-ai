/** Look up a single term. Returns the entry whose LONGEST term-segment
 *  matches the query (so "update mneme" routes to the specific
 *  upgrade entry rather than the generic "Mneme" entry). Null if no
 *  segment matches. */
export function lookupTerm(term: string): DictionaryEntry | null {
  const norm = term.toLowerCase().trim();
  let best: { entry: DictionaryEntry; matchLen: number } | null = null;
  for (const e of MNEME_DICTIONARY) {
    const segs = e.term.toLowerCase().split("/").map((s) => s.trim()).filter(Boolean);
    for (const s of segs) {
      if (norm.includes(s)) {
        if (!best || s.length > best.matchLen) {
          best = { entry: e, matchLen: s.length };
        }
      }
    }
  }
  return best ? best.entry : null;
}

/** Render the dictionary as a markdown block for embedding in directives. */
export function renderDictionary(): string {
  const lines: string[] = [];
  lines.push(`## Mneme dictionary (read this BEFORE interpreting any Mneme keyword)`);
  lines.push(``);
  for (const e of MNEME_DICTIONARY) {
    lines.push(`### ${e.term}`);
    lines.push(`- **Means:** ${e.definition}`);
    if (e.isNot && e.isNot.length > 0) {
      lines.push(`- **Is NOT:** ${e.isNot.map((s) => `"${s}"`).join(", ")}`);
    }
    if (e.example) {
      lines.push(`- **Example:** ${e.example}`);
    }
    lines.push(``);
  }
  return lines.join("\n");
}
